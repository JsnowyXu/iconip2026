#!/usr/bin/env python3
import argparse
import csv
import json
from pathlib import Path


def load_tgb2_csv(path: Path):
    with path.open("r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return next(row for row in rows if row["split"] == "test")


def load_dhc_metrics(path: Path):
    obj = json.loads(path.read_text(encoding="utf-8"))
    return {
        "mrr": float(obj["test"]["mrr"]),
        "auc": float(obj["test"]["auc"]),
        "ap": float(obj["test"]["ap"]),
        "avg_epoch_sec": float(obj["avg_epoch_time_sec"]),
    }


def fmt_triplet(mrr: float, auc: float, ap: float, bold: bool = False) -> str:
    text = f"{mrr:.4f}/{auc:.4f}/{ap:.4f}"
    return f"\\textbf{{{text}}}" if bold else text


def fmt_scalar(value: float, bold: bool = False) -> str:
    text = f"{value:.4f}"
    return f"\\textbf{{{text}}}" if bold else text


def parse_dataset_roots(args) -> list:
    items = []
    if args.dataset_root:
        for raw in args.dataset_root:
            if "=" in raw:
                name, path = raw.split("=", 1)
            else:
                path = raw
                name = Path(path).name
            items.append((name.strip(), Path(path).resolve()))
    elif args.results_root:
        items.append(("thgl_software", Path(args.results_root).resolve()))
    else:
        raise ValueError("provide --results-root or at least one --dataset-root")
    return items


def dataset_label(name: str) -> str:
    mapping = {
        "thgl_github": "github",
        "thgl_software": "software",
    }
    return mapping.get(name, name.replace("thgl_", "").replace("_", "\\_"))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-root", default="", type=str)
    ap.add_argument("--dataset-root", action="append", default=[], help="repeatable: name=/abs/path")
    ap.add_argument("--main-out", required=True, type=str)
    ap.add_argument("--ablation-out", required=True, type=str)
    args = ap.parse_args()

    datasets = []
    for name, root in parse_dataset_roots(args):
        datasets.append(
            {
                "name": name,
                "label": dataset_label(name),
                "root": root,
                "tgb2_trans": load_tgb2_csv(root / "tgb2_custom_trans.csv"),
                "tgb2_ind": load_tgb2_csv(root / "tgb2_custom_ind.csv"),
                "tgb2_edgetype_trans": load_tgb2_csv(root / "tgb2_custom_edgetype_trans.csv"),
                "tgb2_edgetype_ind": load_tgb2_csv(root / "tgb2_custom_edgetype_ind.csv"),
                "sthn_trans": load_tgb2_csv(root / "sthn_trans.csv"),
                "sthn_ind": load_tgb2_csv(root / "sthn_ind.csv"),
                "dhc_trans": load_dhc_metrics(root / "dhc_trans" / "metrics.json"),
                "dhc_ind": load_dhc_metrics(root / "dhc_ind" / "metrics.json"),
                "dhc_no_rel": load_dhc_metrics(root / "dhc_trans_no_rel" / "metrics.json"),
                "dhc_no_comm": load_dhc_metrics(root / "dhc_trans_no_comm" / "metrics.json"),
            }
        )

    main_lines = [
        "% Auto-generated by render_tgb2_thg_tables_to_latex.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Full-dataset TGB2.0 transfer on relation-specific task views extracted from the official \\texttt{thgl\\_github} and \\texttt{thgl\\_software} releases. Metrics are reported as MRR/AUC/AP.}",
        "\\label{tab:tgb2_thg_main}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{llccccc}",
        "\\toprule",
        "Dataset & Setting & TGB2-TGN & TGB2-EdgeType & STHN & DHC & $\\Delta$AP \\\\",
        "\\midrule",
    ]
    for ds in datasets:
        methods_trans = [
            ("tgb2_trans", ds["tgb2_trans"]),
            ("tgb2_edgetype_trans", ds["tgb2_edgetype_trans"]),
            ("sthn_trans", ds["sthn_trans"]),
            ("dhc_trans", ds["dhc_trans"]),
        ]
        methods_ind = [
            ("tgb2_ind", ds["tgb2_ind"]),
            ("tgb2_edgetype_ind", ds["tgb2_edgetype_ind"]),
            ("sthn_ind", ds["sthn_ind"]),
            ("dhc_ind", ds["dhc_ind"]),
        ]
        best_trans_ap = max(float(x[1]["ap"]) for x in methods_trans)
        best_ind_ap = max(float(x[1]["ap"]) for x in methods_ind)
        best_trans_base_ap = max(float(ds["tgb2_trans"]["ap"]), float(ds["tgb2_edgetype_trans"]["ap"]), float(ds["sthn_trans"]["ap"]))
        best_ind_base_ap = max(float(ds["tgb2_ind"]["ap"]), float(ds["tgb2_edgetype_ind"]["ap"]), float(ds["sthn_ind"]["ap"]))
        main_lines.append(
            f"{ds['label']} & Transductive & "
            f"{fmt_triplet(float(ds['tgb2_trans']['mrr']), float(ds['tgb2_trans']['auc']), float(ds['tgb2_trans']['ap']), bold=float(ds['tgb2_trans']['ap']) == best_trans_ap)} & "
            f"{fmt_triplet(float(ds['tgb2_edgetype_trans']['mrr']), float(ds['tgb2_edgetype_trans']['auc']), float(ds['tgb2_edgetype_trans']['ap']), bold=float(ds['tgb2_edgetype_trans']['ap']) == best_trans_ap)} & "
            f"{fmt_triplet(float(ds['sthn_trans']['mrr']), float(ds['sthn_trans']['auc']), float(ds['sthn_trans']['ap']), bold=float(ds['sthn_trans']['ap']) == best_trans_ap)} & "
            f"{fmt_triplet(ds['dhc_trans']['mrr'], ds['dhc_trans']['auc'], ds['dhc_trans']['ap'], bold=float(ds['dhc_trans']['ap']) == best_trans_ap)} & "
            f"{ds['dhc_trans']['ap'] - best_trans_base_ap:+.4f} \\\\"
        )
        main_lines.append(
            f"{ds['label']} & Inductive & "
            f"{fmt_triplet(float(ds['tgb2_ind']['mrr']), float(ds['tgb2_ind']['auc']), float(ds['tgb2_ind']['ap']), bold=float(ds['tgb2_ind']['ap']) == best_ind_ap)} & "
            f"{fmt_triplet(float(ds['tgb2_edgetype_ind']['mrr']), float(ds['tgb2_edgetype_ind']['auc']), float(ds['tgb2_edgetype_ind']['ap']), bold=float(ds['tgb2_edgetype_ind']['ap']) == best_ind_ap)} & "
            f"{fmt_triplet(float(ds['sthn_ind']['mrr']), float(ds['sthn_ind']['auc']), float(ds['sthn_ind']['ap']), bold=float(ds['sthn_ind']['ap']) == best_ind_ap)} & "
            f"{fmt_triplet(ds['dhc_ind']['mrr'], ds['dhc_ind']['auc'], ds['dhc_ind']['ap'], bold=float(ds['dhc_ind']['ap']) == best_ind_ap)} & "
            f"{ds['dhc_ind']['ap'] - best_ind_base_ap:+.4f} \\\\"
        )
    main_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
        ]
    )

    ab_lines = [
        "% Auto-generated by render_tgb2_thg_tables_to_latex.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{DHC ablation on the transductive relation-specific task views extracted from the official TGB2.0 software and GitHub graphs.}",
        "\\label{tab:tgb2_thg_ablation}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Dataset & Variant & MRR & AUC & AP & Avg. epoch (s) \\\\",
        "\\midrule",
    ]
    for ds in datasets:
        variants = [
            ("Full DHC", ds["dhc_trans"]),
            ("No relation memory", ds["dhc_no_rel"]),
            ("No community memory", ds["dhc_no_comm"]),
        ]
        best_mrr = max(x[1]["mrr"] for x in variants)
        best_auc = max(x[1]["auc"] for x in variants)
        best_ap = max(x[1]["ap"] for x in variants)
        for label, vals in variants:
            ab_lines.append(
                f"{ds['label']} & {label} & "
                f"{fmt_scalar(vals['mrr'], bold=vals['mrr'] == best_mrr)} & "
                f"{fmt_scalar(vals['auc'], bold=vals['auc'] == best_auc)} & "
                f"{fmt_scalar(vals['ap'], bold=vals['ap'] == best_ap)} & "
                f"{vals['avg_epoch_sec']:.2f} \\\\"
            )
    ab_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
        ]
    )

    main_out = Path(args.main_out)
    main_out.parent.mkdir(parents=True, exist_ok=True)
    main_out.write_text("\n".join(main_lines) + "\n", encoding="utf-8")

    ablation_out = Path(args.ablation_out)
    ablation_out.parent.mkdir(parents=True, exist_ok=True)
    ablation_out.write_text("\n".join(ab_lines) + "\n", encoding="utf-8")

    print(main_out)
    print(ablation_out)


if __name__ == "__main__":
    main()
