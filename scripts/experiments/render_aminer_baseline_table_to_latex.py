#!/usr/bin/env python3
import argparse
from pathlib import Path

import pandas as pd


METHODS = [
    ("Current(DHC)", "dhc", None),
    ("TGB2-custom(TGN-like)", "tgb2_custom", None),
    ("TGB2-custom(TGN_edgetype)", "tgb2_custom", "tgn_edgetype"),
    ("STHN", "sthn", "sthn"),
    ("DyGLib-custom(TGN-like)", "dyglib_custom", None),
    ("DyGLib-TGN", "dyglib_model_zoo", "TGN"),
    ("DyGLib-TGAT", "dyglib_model_zoo", "TGAT"),
    ("DyGLib-CAWN", "dyglib_model_zoo", "CAWN"),
    ("DyGLib-TCL", "dyglib_model_zoo", "TCL"),
    ("DyGLib-GraphMixer", "dyglib_model_zoo", "GraphMixer"),
    ("DyGLib-DyGFormer", "dyglib_model_zoo", "DyGFormer"),
]


def f(val: float) -> str:
    return f"{float(val):.3f}" if pd.notna(val) else "-"


def cell(auc, ap, f1=None) -> str:
    parts = [f(auc), f(ap)]
    if f1 is not None:
        parts.append(f(f1))
    return "/".join(parts) if any(x != "-" for x in parts) else "-"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dhc-aggregate-csv", required=True, type=str)
    ap.add_argument("--baseline-summary-csv", required=True, type=str)
    ap.add_argument("--out-tex", required=True, type=str)
    args = ap.parse_args()

    dhc = pd.read_csv(args.dhc_aggregate_csv)
    dhc = dhc[(dhc["dataset"] == "aminer_paper") & (dhc["variant"] == "full")].copy()
    dhc_map = {row["task_type"]: row for _, row in dhc.iterrows()}

    base = pd.read_csv(args.baseline_summary_csv)
    base = base[base["dataset"] == "aminer_paper"].copy()

    rows = []
    for label, family, model in METHODS:
        if family == "dhc":
            trans = dhc_map.get("edge_transductive", {})
            ind = dhc_map.get("edge_inductive", {})
            node = dhc_map.get("node_multilabel", {})
            rows.append(
                {
                    "Method": label,
                    "Transductive (AUC/AP)": cell(trans.get("test_auc_mean"), trans.get("test_ap_mean")),
                    "Inductive (AUC/AP)": cell(ind.get("test_auc_mean"), ind.get("test_ap_mean")),
                    "Node-ML (AUC/AP/F1)": cell(
                        node.get("test_auc_mean"),
                        node.get("test_ap_mean"),
                        node.get("node_ml_micro_f1_mean"),
                    ),
                }
            )
            continue

        sub = base[base["family"] == family].copy()
        if model is not None:
            sub = sub[sub["model"] == model].copy()
        if sub.empty:
            continue

        trans = sub[sub["task_type"] == "edge_transductive"]
        ind = sub[sub["task_type"] == "edge_inductive"]
        node = sub[sub["task_type"] == "node_multilabel"]
        rows.append(
            {
                "Method": label,
                "Transductive (AUC/AP)": cell(trans["best_test_auc"].max(), trans["best_test_ap"].max()),
                "Inductive (AUC/AP)": cell(ind["best_test_auc"].max(), ind["best_test_ap"].max()),
                "Node-ML (AUC/AP/F1)": cell(
                    node["best_test_auc"].max(),
                    node["best_test_ap"].max(),
                    node["best_node_ml_micro_f1"].max(),
                ),
            }
        )

    df = pd.DataFrame(rows)
    tex = df.to_latex(index=False, escape=True, longtable=False)
    lines = [
        "% Auto-generated by render_aminer_baseline_table_to_latex.py",
        "\\begin{table*}[t]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\caption{AMiner heterogeneous-graph comparison. Link columns report AUC/AP. Node-ML reports AUC/AP/micro-F1.}",
        "\\label{tab:aminer_baselines}",
        "\\resizebox{\\textwidth}{!}{%",
        tex.rstrip(),
        "}%",
        "\\end{table*}",
    ]

    out = Path(args.out_tex)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
