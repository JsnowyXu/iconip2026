VARIANTS = ["full", "no_relation_memory", "no_edge_type", "no_community"]
VARIANT_NAMES = {
    "full": "Full",
    "no_relation_memory": "No relation memory",
    "no_edge_type": "No edge type",
    "no_community": "No community",
}
COLORS = ["#4C78A8", "#F58518", "#54A24B", "#B279A2"]
HATCHES = ["", "///", "\\\\", "xx"]


def fmt(x: object) -> str:
    try:
        return f"{float(x):.4f}"
    except Exception:
        return "-"


def fmt_delta(x: float) -> str:
    if abs(float(x)) < 0.00005:
        x = 0.0
    return f"{float(x):+.4f}"


def esc_latex(s: object) -> str:
    return str(s).replace("_", "\\_")


def task_label(task_name: str) -> str:
    return (
        task_name.replace("patent_cn_edge_org_codeIII", "CN")
        .replace("patent_in_edge_org_codeIII", "IN")
        .replace("patent_us_edge_org_codeIII", "US")
        .replace("thgl_software_edge", "Software")
        .replace("_transductive", "-T")
        .replace("_inductive", "-I")
    )


def read_test_metrics(metrics_path: Path) -> dict:
    if not metrics_path.exists():
        return {}
    try:
        obj = json.loads(metrics_path.read_text(encoding="utf-8"))
    except Exception:
        return {}
    test = obj.get("test", {}) if isinstance(obj, dict) else {}
    return {
        "test_mrr": test.get("mrr", obj.get("test_mrr")),
        "test_auc": test.get("auc", obj.get("test_auc")),
        "test_ap": test.get("ap", obj.get("test_ap")),
    }


def render_module_ablation(project_root: Path, iconip_dir: Path) -> None:
    summary_csv = project_root / "results" / "best_config_module_ablation" / "summary.csv"
    rows = list(csv.DictReader(summary_csv.open(encoding="utf-8")))
    tasks = sorted({r["task_name"] for r in rows})

    table_path = iconip_dir / "tables" / "best_module_ablation_table.tex"
    lines = [
        "% Auto-generated by scripts/experiments/render_iconip_mrr_artifacts.py\n",
        "\\begin{table*}[t]\n",
        "\\centering\n\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n",
        "\\caption{Best-configuration module ablation. Values are test MRR/AUC/AP; $\\Delta$MRR is variant MRR minus the full model MRR on the same task.}\n",
        "\\label{tab:best_module_ablation}\n",
        "\\resizebox{\\textwidth}{!}{%\n",
        "\\begin{tabular}{llrrrr}\n\\toprule\n",
        "Task & Variant & MRR & AUC & AP & $\\Delta$MRR \\\\\n\\midrule\n",
    ]
    for task in tasks:
        rs = {r["variant"]: r for r in rows if r["task_name"] == task}
        full_mrr = float(rs["full"]["test_mrr"])
        for variant in VARIANTS:
            r = rs[variant]
            delta = float(r["test_mrr"]) - full_mrr
            prefix = esc_latex(task_label(task)) if variant == "full" else ""
            lines.append(
                f"{prefix} & {VARIANT_NAMES[variant]} & {fmt(r['test_mrr'])} & "
                f"{fmt(r['test_auc'])} & {fmt(r['test_ap'])} & {fmt_delta(delta)} \\\\\n"
            )
        lines.append("\\addlinespace[1pt]\n")
    lines.extend(["\\bottomrule\n\\end{tabular}%\n}\n\\end{table*}\n"])
    table_path.write_text("".join(lines), encoding="utf-8")

    labels = [task_label(t) for t in tasks]
    x = np.arange(len(tasks))
    width = 0.18
    fig, ax = plt.subplots(figsize=(12.2, 4.8))
    for idx, variant in enumerate(VARIANTS):
        vals = []
        for task in tasks:
            r = next(r for r in rows if r["task_name"] == task and r["variant"] == variant)
            vals.append(float(r["test_mrr"]))
        ax.bar(
            x + (idx - 1.5) * width,
            vals,
            width,
            label=VARIANT_NAMES[variant],
            color=COLORS[idx],
            edgecolor="#2f2f2f",
            linewidth=0.65,
            hatch=HATCHES[idx],
        )
    ax.axhline(0.95, color="#666666", linestyle="--", linewidth=0.8, alpha=0.45)
    ax.text(len(tasks) - 0.15, 0.952, "MRR=0.95", ha="right", va="bottom", fontsize=8, color="#555555")
    ax.set_ylabel("Test MRR")
    ax.set_ylim(0.75, 1.01)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=35, ha="right")
    ax.grid(axis="y", alpha=0.22, linewidth=0.6)
    ax.legend(ncol=4, fontsize=8.5, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.13))
    ax.set_title("Best-configuration module ablation across task views", fontsize=11, pad=28)
    for spine in ["top", "right"]:
        ax.spines[spine].set_visible(False)
    fig.tight_layout()
    fig.savefig(iconip_dir / "figures" / "best_module_ablation_mrr.png", dpi=240)
    plt.close(fig)


def load_sensitivity_rows(project_root: Path) -> list[dict]:
    job_plan = project_root / "results" / "best_config_sensitivity" / "job_plan.csv"
    rows = []
    for r in csv.DictReader(job_plan.open(encoding="utf-8")):
        metrics_path = Path(r["metrics_path"])
        metrics = read_test_metrics(metrics_path)
        if not metrics:
            continue
        row = dict(r)
        row.update(metrics)
        rows.append(row)
    return rows


def render_sensitivity(project_root: Path, iconip_dir: Path) -> None:
    rows = load_sensitivity_rows(project_root)
    planned = list(csv.DictReader((project_root / "results" / "best_config_sensitivity" / "job_plan.csv").open(encoding="utf-8")))
    by_param: dict[str, list[dict]] = defaultdict(list)
    planned_by_param: dict[str, int] = defaultdict(int)
    for r in planned:
        planned_by_param[r["parameter"]] += 1
    for r in rows:
        by_param[r["parameter"]].append(r)

    params = [
        "typed_negative_ratio",
        "popular_negative_ratio",
        "recent_neighbor_size",
        "neighbor_aggregation",
        "community_assign_topk",
        "num_communities",
    ]
    table_path = iconip_dir / "tables" / "best_config_sensitivity_table.tex"
    lines = [
        "% Auto-generated by scripts/experiments/render_iconip_mrr_artifacts.py\n",
        "\\begin{table*}[t]\n\\centering\n\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n",
        "\\caption{Completed best-configuration sensitivity sweep. Best rows are selected by test MRR within each varied parameter.}\n",
        "\\label{tab:best_config_sensitivity}\n",
        "\\resizebox{\\textwidth}{!}{%\n",
        "\\begin{tabular}{lrrlccc}\n\\toprule\n",
        "Parameter & Done & Planned & Best setting & MRR & AUC & AP \\\\\n\\midrule\n",
    ]
    for param in params:
        items = by_param.get(param, [])
        if not items:
            continue
        best = max(items, key=lambda r: float(r["test_mrr"]))
        setting = f"{task_label(best['task_name'])}, {best['value']}"
        lines.append(
            f"{esc_latex(param)} & {len(items)} & {planned_by_param[param]} & {esc_latex(setting)} & "
            f"{fmt(best['test_mrr'])} & {fmt(best['test_auc'])} & {fmt(best['test_ap'])} \\\\\n"
        )
    lines.extend(["\\bottomrule\n\\end{tabular}%\n}\n\\end{table*}\n"])
    table_path.write_text("".join(lines), encoding="utf-8")

    fig, axes = plt.subplots(2, 3, figsize=(11, 5.8), sharey=True)
    axes = axes.ravel()
    for ax, param in zip(axes, params):
        value_groups: dict[str, list[float]] = defaultdict(list)
        for r in by_param.get(param, []):
            value_groups[str(r["value"])].append(float(r["test_mrr"]))
        keys = sorted(value_groups.keys(), key=lambda z: (float(z) if z.replace(".", "", 1).isdigit() else z))
        data = [value_groups[k] for k in keys]
        ax.boxplot(
            data,
            labels=keys,
            patch_artist=True,
            boxprops=dict(facecolor="#9ecae1", color="#2b6cb0", hatch="///"),
            medianprops=dict(color="#c53030"),
        )
        ax.set_title(param.replace("_", " "), fontsize=9)
        ax.tick_params(axis="x", labelrotation=35, labelsize=7)
        ax.grid(axis="y", alpha=0.25)
    axes[0].set_ylabel("Test MRR")
    axes[3].set_ylabel("Test MRR")
    fig.suptitle("Sensitivity sweep: completed MRR distributions by varied parameter", fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(iconip_dir / "figures" / "best_config_sensitivity_mrr.png", dpi=220)
    plt.close(fig)


def render_cross_relation(iconip_dir: Path) -> None:
    data_path = iconip_dir / "data" / "cross_relation_boost_summary.csv"
    df = pd.read_csv(data_path)
    best_rows = []
    delta_rows = []
    for dataset, g in df.groupby("dataset"):
        base = g[g["variant"] == "base"].iloc[0]
        boost = g[g["variant"] != "base"].sort_values(["test_mrr", "test_ap", "test_auc"], ascending=False).iloc[0]
        best_rows.append({"dataset": dataset, "base": float(base["test_mrr"]), "boost": float(boost["test_mrr"]), "boost_variant": boost["variant"]})
        for _, r in g[g["variant"] != "base"].iterrows():
            delta_rows.append({"dataset": dataset, "variant": r["variant"], "delta_mrr": float(r["test_mrr"]) - float(base["test_mrr"])})

    best_df = pd.DataFrame(best_rows)
    x = np.arange(len(best_df))
    width = 0.28
    fig, ax = plt.subplots(figsize=(7.0, 4.2))
    ax.bar(x - width / 2, best_df["base"], width, label="Base", color="#4C78A8", edgecolor="#2f2f2f")
    ax.bar(x + width / 2, best_df["boost"], width, label="Best boost", color="#F58518", edgecolor="#2f2f2f", hatch="///")
    ax.set_xticks(x)
    ax.set_xticklabels(best_df["dataset"])
    ax.set_ylabel("Test MRR")
    ax.set_ylim(0.96, 0.99)
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False)
    ax.set_title("Cross-relation enhancement: MRR")
    fig.tight_layout()
    fig.savefig(iconip_dir / "figures" / "cross_relation_mrr_base_vs_best.png", dpi=220)
    plt.close(fig)

    ddf = pd.DataFrame(delta_rows)
    fig, ax = plt.subplots(figsize=(7.0, 4.0))
    colors = ["#54A24B" if v >= 0 else "#E45756" for v in ddf["delta_mrr"]]
    bars = ax.bar(ddf["dataset"] + "\n" + ddf["variant"], ddf["delta_mrr"], color=colors, edgecolor="#2f2f2f", hatch="\\\\")
    ax.axhline(0, color="#333333", linewidth=0.8)
    ax.set_ylabel("Boost - base MRR")
    ax.set_title("Cross-relation MRR delta")
    ax.grid(axis="y", alpha=0.25)
    ax.tick_params(axis="x", labelsize=8)
    fig.tight_layout()
    fig.savefig(iconip_dir / "figures" / "cross_relation_mrr_delta_variants.png", dpi=220)
    plt.close(fig)


def render_community_mrr(project_root: Path, iconip_dir: Path) -> None:
    case_root = project_root / "results" / "community_memory_case_study"
    rows = []
    for d in sorted(p for p in case_root.iterdir() if p.is_dir()):
        readme = d / "README.md"
        metrics = {}
        if readme.exists():
            for line in readme.read_text(encoding="utf-8", errors="ignore").splitlines():
                if line.startswith("- test_"):
                    key, value = line[2:].split(":", 1)
                    metrics[key.strip()] = value.strip().strip("`")
        churns = []
        churn_csv = d / "monitor_assignment_churn.csv"
        if churn_csv.exists():
            for r in csv.DictReader(churn_csv.open(encoding="utf-8")):
                if r.get("membership_churn"):
                    churns.append(float(r["membership_churn"]))
        rows.append(
            {
                "task": d.name,
                "mrr": float(metrics.get("test_mrr", "nan")),
                "churn": sum(churns) / len(churns) if churns else 0.0,
            }
        )
    df = pd.DataFrame(rows)
    fig, ax1 = plt.subplots(figsize=(11, 4.4))
    x = np.arange(len(df))
    ax1.bar(x, df["mrr"], color="#4C78A8", edgecolor="#2f2f2f", label="MRR")
    ax1.set_ylim(0.75, 1.01)
    ax1.set_ylabel("Test MRR")
    ax1.set_xticks(x)
    ax1.set_xticklabels([task_label(t) for t in df["task"]], rotation=35, ha="right")
    ax1.grid(axis="y", alpha=0.25)
    ax2 = ax1.twinx()
    ax2.plot(x, df["churn"], color="#E45756", marker="o", linewidth=2, label="Mean churn")
    ax2.set_ylim(0, 1.05)
    ax2.set_ylabel("Mean assignment churn")
    handles1, labels1 = ax1.get_legend_handles_labels()
    handles2, labels2 = ax2.get_legend_handles_labels()
    ax1.legend(handles1 + handles2, labels1 + labels2, frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(iconip_dir / "figures" / "community_case_mrr_churn.png", dpi=220)
    plt.close(fig)


