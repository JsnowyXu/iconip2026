#!/usr/bin/env python3
import argparse
from pathlib import Path

import pandas as pd


def f4(x):
    if pd.isna(x):
        return "--"
    return f"{float(x):.4f}"


def esc(s):
    return str(s).replace("_", "\\_")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary-csv", required=True, type=str)
    ap.add_argument("--out-tex", required=True, type=str)
    args = ap.parse_args()

    df = pd.read_csv(args.summary_csv)

    full = df[df["name"].str.endswith("_full")].copy()
    ab_trans = df[df["name"].str.startswith("cn_trans_")].copy()
    ab_node = df[df["name"].str.startswith("cn_node_")].copy()

    parts = []
    parts.append("% Auto-generated by scripts/experiments/render_cuda_tables_to_latex.py")

    parts.append("\\begin{table}[ht]")
    parts.append("\\centering")
    parts.append("\\caption{CUDA main-task results with early stop (patience=10).}")
    parts.append("\\begin{tabular}{lcccccc}")
    parts.append("\\toprule")
    parts.append("Run & BestEp & StopEp & MRR & AUC & AP & Epoch(s) \\\\")
    parts.append("\\midrule")
    for _, r in full.iterrows():
        parts.append(
            f"{esc(r['name'])} & {int(r['best_epoch'])} & {int(r['stopped_epoch'])} & "
            f"{f4(r['test_mrr'])} & {f4(r['test_auc'])} & {f4(r['test_ap'])} & {f4(r['avg_epoch_time_sec'])} \\\\"
        )
    parts.append("\\bottomrule")
    parts.append("\\end{tabular}")
    parts.append("\\end{table}")

    parts.append("\\begin{table}[ht]")
    parts.append("\\centering")
    parts.append("\\caption{Ablations on CN transductive task (CUDA).}")
    parts.append("\\begin{tabular}{lccccc}")
    parts.append("\\toprule")
    parts.append("Variant & BestEp & MRR & AUC & AP & Throughput \\\\")
    parts.append("\\midrule")
    for _, r in ab_trans.iterrows():
        parts.append(
            f"{esc(r['name'])} & {int(r['best_epoch'])} & {f4(r['test_mrr'])} & {f4(r['test_auc'])} & "
            f"{f4(r['test_ap'])} & {f4(r['train_edges_per_sec'])} \\\\"
        )
    parts.append("\\bottomrule")
    parts.append("\\end{tabular}")
    parts.append("\\end{table}")

    parts.append("\\begin{table}[ht]")
    parts.append("\\centering")
    parts.append("\\caption{Ablations on CN node-task view (CUDA).}")
    parts.append("\\begin{tabular}{lcccccc}")
    parts.append("\\toprule")
    parts.append("Variant & BestEp & MRR & AUC & AP & Micro-F1 & mAP \\\\")
    parts.append("\\midrule")
    for _, r in ab_node.iterrows():
        parts.append(
            f"{esc(r['name'])} & {int(r['best_epoch'])} & {f4(r['test_mrr'])} & {f4(r['test_auc'])} & "
            f"{f4(r['test_ap'])} & {f4(r['node_ml_micro_f1'])} & {f4(r['node_ml_map'])} \\\\"
        )
    parts.append("\\bottomrule")
    parts.append("\\end{tabular}")
    parts.append("\\end{table}")

    out = Path(args.out_tex)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
