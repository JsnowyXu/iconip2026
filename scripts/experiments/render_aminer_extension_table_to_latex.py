#!/usr/bin/env python3
import argparse
from pathlib import Path

import pandas as pd


def fmt_triplet(mrr_mean, mrr_std, auc_mean, auc_std, ap_mean, ap_std) -> str:
    return (
        f"{float(mrr_mean):.3f}$\\pm${float(mrr_std):.3f}/"
        f"{float(auc_mean):.3f}$\\pm${float(auc_std):.3f}/"
        f"{float(ap_mean):.3f}$\\pm${float(ap_std):.3f}"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--aggregate-csv", required=True, type=str)
    ap.add_argument("--out-tex", required=True, type=str)
    args = ap.parse_args()

    df = pd.read_csv(args.aggregate_csv)
    df = df[(df["dataset"] == "aminer_paper") & (df["variant"] == "full")].copy()
    if df.empty:
        raise SystemExit("no aminer_paper rows found in aggregate csv")

    by_task = {row["task_type"]: row for _, row in df.iterrows()}
    trans = by_task["edge_transductive"]
    ind = by_task["edge_inductive"]
    node = by_task["node_multilabel"]

    lines = [
        "% Auto-generated by render_aminer_extension_table_to_latex.py",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Additional results on the AMiner heterogeneous graph (mean$\\pm$std over three seeds).}",
        "\\label{tab:aminer_extension}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Dataset & Transductive (MRR/AUC/AP) & Inductive (MRR/AUC/AP) & Node-ML (AUC/AP/F1) \\\\",
        "\\midrule",
        (
            "aminer\\_paper"
            f" & {fmt_triplet(trans['test_mrr_mean'], trans['test_mrr_std'], trans['test_auc_mean'], trans['test_auc_std'], trans['test_ap_mean'], trans['test_ap_std'])}"
            f" & {fmt_triplet(ind['test_mrr_mean'], ind['test_mrr_std'], ind['test_auc_mean'], ind['test_auc_std'], ind['test_ap_mean'], ind['test_ap_std'])}"
            f" & {float(node['test_auc_mean']):.3f}$\\pm${float(node['test_auc_std']):.3f}/"
            f"{float(node['test_ap_mean']):.3f}$\\pm${float(node['test_ap_std']):.3f}/"
            f"{float(node['node_ml_micro_f1_mean']):.3f}$\\pm${float(node['node_ml_micro_f1_std']):.3f} \\\\"
        ),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]

    out = Path(args.out_tex)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
