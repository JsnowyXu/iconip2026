#!/usr/bin/env python3
import argparse
from pathlib import Path

import pandas as pd


def f4(x):
    if pd.isna(x):
        return "--"
    return f"{float(x):.4f}"


def esc(s):
    return str(s).replace("_", "\\_")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary-csv", required=True, type=str)
    ap.add_argument("--out-tex", required=True, type=str)
    args = ap.parse_args()

    df = pd.read_csv(args.summary_csv)
    full = df[df["name"].str.endswith("_full")].copy()
    ab_trans = df[df["name"].str.startswith("dblp_trans_")].copy()
    ab_node = df[df["name"].str.startswith("dblp_node_")].copy()

    parts = ["% Auto-generated by render_cuda_academic_tables_to_latex.py"]

    parts += [
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{Academic datasets (arXiv/DBLP) CUDA results with early stop (patience=10).}",
        "\\begin{tabular}{lccccccc}",
        "\\toprule",
        "Run & BestEp & StopEp & MRR & AUC & AP & Micro-F1 & mAP \\\\",
        "\\midrule",
    ]
    for _, r in full.iterrows():
        parts.append(
            f"{esc(r['name'])} & {int(r['best_epoch'])} & {int(r['stopped_epoch'])} & "
            f"{f4(r['test_mrr'])} & {f4(r['test_auc'])} & {f4(r['test_ap'])} & "
            f"{f4(r['node_ml_micro_f1'])} & {f4(r['node_ml_map'])} \\\\"
        )
    parts += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    parts += [
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{DBLP transductive ablation (CUDA).}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Variant & MRR & AUC & AP & Throughput \\\\",
        "\\midrule",
    ]
    for _, r in ab_trans.iterrows():
        parts.append(
            f"{esc(r['name'])} & {f4(r['test_mrr'])} & {f4(r['test_auc'])} & {f4(r['test_ap'])} & {f4(r['train_edges_per_sec'])} \\\\"
        )
    parts += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    parts += [
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{DBLP node-task ablation (CUDA).}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Variant & MRR & AUC & AP & Micro-F1 & mAP \\\\",
        "\\midrule",
    ]
    for _, r in ab_node.iterrows():
        parts.append(
            f"{esc(r['name'])} & {f4(r['test_mrr'])} & {f4(r['test_auc'])} & {f4(r['test_ap'])} & "
            f"{f4(r['node_ml_micro_f1'])} & {f4(r['node_ml_map'])} \\\\"
        )
    parts += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    out = Path(args.out_tex)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
